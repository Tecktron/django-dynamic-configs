"""Regenerate ``src/dynamic_configs/types/iso4217.py`` from SIX Group's ISO 4217 List One.

Run by hand, or monthly from the GitHub workflow, which opens a pull request when the list changed::

    python scripts/update_currencies.py [--from FILE] [--out PATH] [--summary PATH]

The module is rewritten only when the suggested currencies (codes or names) differ from the current ones, not when
only the publication date does.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.request import urlopen

SOURCE = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml"


def parse(xml: bytes, minimum: int = 100) -> tuple[str, dict[str, str]]:
    """Return the publication date and the suggested currencies (code to ISO name, sorted by code).

    Entries with no code (Antarctica and the like), funds (``IsFund="true"``) and the ``ZZ`` entries (metals, bond
    units, testing, no currency) are left out. Raises ``ValueError`` on anything that is not List One, or that holds
    fewer than ``minimum`` currencies (a partial download).
    """
    try:
        root = ET.fromstring(xml)  # noqa: S314 (SIX over HTTPS, a reviewed PR follows, expat refuses entity attacks)
    except ET.ParseError as error:
        raise ValueError(f"Not well-formed XML: {error}") from error
    if root.tag != "ISO_4217":
        raise ValueError(f"Not an ISO 4217 list: the root element is {root.tag!r}")
    published = root.get("Pblshd")
    if not published:
        raise ValueError("The list has no publication date (Pblshd)")

    currencies: dict[str, str] = {}
    for item in root.iter("CcyNtry"):
        code = (item.findtext("Ccy") or "").strip()
        name_element = item.find("CcyNm")
        is_fund = name_element is not None and name_element.get("IsFund") == "true"
        if not code or is_fund or (item.findtext("CtryNm") or "").strip().startswith("ZZ"):
            continue
        if not re.fullmatch(r"[A-Z]{3}", code):
            raise ValueError(f"Not a currency code: {code!r}")
        name = (item.findtext("CcyNm") or "").strip()
        if not name:
            raise ValueError(f"No name for {code}")
        if currencies.setdefault(code, name) != name:
            raise ValueError(f"{code} has two names: {currencies[code]!r} and {name!r}")
    if len(currencies) < minimum:
        raise ValueError(f"Only {len(currencies)} currencies, expected at least {minimum}: a partial download?")
    return published, dict(sorted(currencies.items()))


def render(published: str, currencies: dict[str, str]) -> str:
    """Return the source of the data module, formatted as ruff format would."""
    lines = [
        '"""The ISO 4217 currencies suggested for ``money_currency``, as ISO publishes their names.',
        "",
        "Generated by ``scripts/update_currencies.py`` from SIX Group's ISO 4217 List One; don't edit it by hand.",
        "Funds, metals, bond units, testing and no-currency entries are left out.",
        '"""',
        "",
        f"PUBLISHED = {json.dumps(published)}",
        f"SOURCE = {json.dumps(SOURCE)}",
        "CURRENCIES = {",
        *(f"    {json.dumps(code)}: {json.dumps(name, ensure_ascii=False)}," for code, name in currencies.items()),
        "}",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Fetch (or read) List One and rewrite the module when the suggested currencies changed."""

    def current(path: Path) -> dict[str, str]:
        """Return the ``CURRENCIES`` of the module at ``path`` without importing it, or ``{}`` if it is missing."""
        if not path.exists():
            return {}
        for node in ast.parse(path.read_text()).body:
            if isinstance(node, ast.Assign) and [target.id for target in node.targets] == ["CURRENCIES"]:
                return ast.literal_eval(node.value)
        raise ValueError(f"{path} has no CURRENCIES")

    def summarize(old: dict[str, str], new: dict[str, str]) -> str:
        """Describe how ``new`` differs from ``old``, or ``unchanged``."""
        added = [f"{code} ({new[code]})" for code in new if code not in old]
        removed = [f"{code} ({old[code]})" for code in old if code not in new]
        renamed = [f"{code} ({old[code]} -> {new[code]})" for code in new if code in old and old[code] != new[code]]
        lines = [
            f"{label}: {', '.join(items)}"
            for label, items in (("added", added), ("removed", removed), ("renamed", renamed))
            if items
        ]
        return "\n".join(lines) or "unchanged"

    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--from", dest="source", type=Path, help="read this List One file instead of fetching SOURCE")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "src" / "dynamic_configs" / "types" / "iso4217.py",
        help="the module to write (default: the package's)",
    )
    parser.add_argument("--summary", type=Path, help="also write the summary to this file")
    arguments = parser.parse_args(argv)

    if arguments.source:
        xml = arguments.source.read_bytes()
    else:
        with urlopen(SOURCE, timeout=60) as response:  # noqa: S310 (a constant https URL)
            xml = response.read()
    published, currencies = parse(xml)

    old = current(arguments.out)
    summary = summarize(old, currencies)
    if currencies != old:
        arguments.out.write_text(render(published, currencies))
    print(summary)
    if arguments.summary:
        arguments.summary.write_text(summary + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
